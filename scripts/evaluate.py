"""Regenerate the evaluation report from a fresh synthetic dataset.

Usage:  python scripts/evaluate.py
Writes docs/evaluation-results.json and docs/evaluation.md.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sharetally import db, synthetic  # noqa: E402
from sharetally.engine.ledger import ENGINE_VERSION  # noqa: E402
from sharetally.evaluation import evaluate  # noqa: E402


def main() -> None:
    conn = db.connect(":memory:")
    db.init_schema(conn)
    db.seed(conn, synthetic.build_dataset())
    ev = evaluate(conn)
    out = ROOT / "docs"
    out.mkdir(exist_ok=True)
    (out / "evaluation-results.json").write_text(json.dumps(ev, indent=2, ensure_ascii=False), encoding="utf-8")

    b = ev["baseline"]
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `python scripts/evaluate.py` · engine v{ENGINE_VERSION} · demo clock {ev['as_of']} · "
        f"synthetic seed {synthetic.SEED}.",
        "",
        "These numbers come from synthetic scenarios whose expected results were written next to the data before "
        "the engine ran, by the same team that wrote the rules. They show that the mechanism behaves as designed. "
        "They are **not** a measure of real-world accuracy.",
        "",
        "| Measure | Result |",
        "| --- | ---: |",
        f"| Expected status and finding codes matched (plots + cases) | {ev['passed']} / {ev['objects']} |",
        f"| Clean background plots wrongly flagged | {ev['background_false_flags']} / {ev['background_plots']} |",
        f"| Incomplete-data objects reported as clean | {ev['false_clean_on_incomplete']} / {ev['incomplete_expected']} |",
        f"| Flags citing at least one source record | {ev['flags_with_evidence']} / {ev['flags_total']} |",
        f"| Slowest single-plot ledger | {ev['latency_ms']['max']} ms (mean {ev['latency_ms']['mean']} ms, "
        f"{ev['latency_ms']['plots']} plots) |",
        "",
        "## Compared with a khatian-only check",
        "",
        f"A check that only asks \"is the transferor in the latest khatian with enough area?\" would clear "
        f"**{len(b['cleared_by_baseline'])} of {b['problem_cases']}** pending cases that ShareTally holds as conflict "
        f"or incomplete ({', '.join(b['cleared_by_baseline']) or 'none'}), and hold "
        f"**{len(b['held_by_baseline'])} of {b['clean_cases']}** clean cases "
        f"({', '.join(b['held_by_baseline']) or 'none'}).",
        "",
        "## Per finding code (plots)",
        "",
        "| Code | Correctly raised | Raised, not expected | Expected, missed |",
        "| --- | ---: | ---: | ---: |",
        *[f"| `{code}` | {c['tp']} | {c['fp']} | {c['fn']} |" for code, c in ev["per_code"].items()],
        "",
        "## Scenario results",
        "",
        "| Object | Scenario | Expected | Actual | Codes | Match |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in ev["rows"]:
        if r["scenario"] == "BG":
            continue
        lines.append(f"| {r['object_type']} `{r['object_id']}` | {r['scenario']}: {r['description']} | "
                     f"{r['expected_status']} | {r['actual_status']} | {', '.join(r['actual_codes']) or '—'} | "
                     f"{'yes' if r['pass'] else 'NO'} |")
    lines.append("")
    lines.append(f"Background objects (generated clean plots and their cases): "
                 f"{sum(1 for r in ev['rows'] if r['scenario'] == 'BG')}, all included in the totals above.")
    (out / "evaluation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{ev['passed']}/{ev['objects']} matched; report written to docs/evaluation.md")


if __name__ == "__main__":
    main()
